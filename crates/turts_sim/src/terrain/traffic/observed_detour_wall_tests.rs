fn fixture(invert: bool, cohort: &[(u32, [f32; 2], [f32; 2])]) -> MovementFrame {
    let mut frame = tests::fixture(false);
    frame.units.clear();
    for &(id, from, to) in cohort {
        frame.units.push(MovementFrameUnit {
            unit_id: if invert { 10000 - id } else { id },
            owner_slot: 0,
            unit_type: 1,
            position: Vec2::from_array(from),
            radius: 0.3,
            speed: Some(100.),
            target: Some(Vec2::from_array(to)),
            progress: None,
            plain_progress: None,
            physical_escape: None,
        });
    }
    for y in 0..10 {
        for x in 0..10 {
            let id = 701 + y * 10 + x;
            frame.units.push(MovementFrameUnit {
                unit_id: if invert { 10000 - id } else { id },
                owner_slot: 1,
                unit_type: 2,
                position: Vec2::new(60.625 + x as f32 * 0.75, 28.625 + y as f32 * 0.75),
                radius: 0.3,
                speed: None,
                target: None,
                progress: None,
                plain_progress: None,
                physical_escape: None,
            });
        }
    }
    if invert {
        frame.units.reverse();
    }
    frame
}
#[test]
fn returning_cohort_passes_the_disclosed_wall_without_sharing_one_corner() {
    let mut completed = Vec::new();
    for invert in [false, true] {
        let mut frame = fixture(invert, COHORT);
        let mut state = TrafficState::default();
        for tick in 11..=20 {
            cohort_step(&mut frame, &mut state, tick, invert);
        }
        let mut result = Vec::new();
        for id in [15, 16, 31, 47] {
            let actor = frame
                .units
                .iter()
                .find(|u| u.unit_id == if invert { 10000 - id } else { id })
                .unwrap();
            result.push(actor.position);
            assert!(
                actor.position.x < 55.,
                "scout{id} must clear the wall's sight neighborhood in the frozen ten return ticks; got {:?}",
                actor.position
            );
        }
        completed.push(result);
    }
    assert_eq!(completed[0], completed[1]);
}

fn cohort_step(frame: &mut MovementFrame, state: &mut TrafficState, tick: u32, invert: bool) {
    let mut advice = frame.clone();
    let mut budget = crate::movement::sweep::SweepBudget::new(tick);
    apply_with_observed_detours(
        frame,
        &mut advice,
        0.05,
        tick,
        state,
        |_, _, _| true,
        |_, _, _, _| EntranceContact::Outside,
        |_| false,
        &mut budget,
        |viewer, id| {
            frame
                .units
                .iter()
                .find(|u| u.unit_id == id && u.owner_slot != viewer)
                .map(|u| ObservedBody {
                    position: u.position,
                    radius: u.radius,
                })
        },
        |_| true,
        |viewer, sink| {
            for row in frame.units.iter().filter(|u| u.owner_slot != viewer) {
                if !sink(
                    row.unit_id,
                    ObservedBody {
                        position: row.position,
                        radius: row.radius,
                    },
                ) {
                    return false;
                }
            }
            true
        },
    );
    let outputs =
        crate::movement::step_frame_with_sweep_budget(&advice, 0.05, &BTreeSet::new(), &mut budget);
    assert!(budget.pairs.iter().sum::<usize>() <= VISITS);
    assert!(state.tick_neighbors <= VISITS / 2);
    if tick == 11 || tick == 20 {
        eprintln!(
            "cohort tick{tick}: {:?}",
            frame
                .units
                .iter()
                .filter(|u| [15, 16, 31, 47].contains(&if invert {
                    10000 - u.unit_id
                } else {
                    u.unit_id
                }))
                .map(|u| (
                    u.unit_id,
                    u.position,
                    state
                        .members
                        .get(&u.unit_id)
                        .and_then(|m| m.local_detour)
                        .map(|r| r.route.corners)
                ))
                .collect::<Vec<_>>()
        );
    }
    for unit in &mut frame.units {
        let output = outputs
            .iter()
            .find(|out| out.unit_id == unit.unit_id)
            .unwrap();
        // Exact continuous safety for all four causal scouts against
        // EVERY body, including moving own cohort trajectories.
        let authored = if invert {
            10000 - unit.unit_id
        } else {
            unit.unit_id
        };
        if [15, 16, 31, 47].contains(&authored) {
            for body in advice
                .units
                .iter()
                .filter(|body| body.unit_id != unit.unit_id)
            {
                let other = outputs
                    .iter()
                    .find(|out| out.unit_id == body.unit_id)
                    .unwrap();
                assert!(
                    swept_disks_clear(
                        point(unit.position),
                        point(output.position),
                        unit.radius.into(),
                        point(body.position),
                        point(other.position),
                        body.radius.into(),
                        &mut Budget::new(1)
                    )
                    .unwrap()
                );
            }
        }
        unit.position = output.position;
    }
}

fn scout_positions(frame: &MovementFrame, invert: bool, tick: u32) -> Vec<Vec2> {
    let result = [15, 16, 31, 47].map(|id| {
        frame
            .units
            .iter()
            .find(|u| u.unit_id == if invert { 10000 - id } else { id })
            .unwrap()
            .position
    });
    eprintln!("return tick{tick} scouts {result:?}");
    for (id, p) in [15, 16, 31, 47].into_iter().zip(result) {
        assert!(
            p.x < 55.,
            "scout{id} still sees the wall at return tick{tick}: {p:?}"
        );
    }
    result.to_vec()
}
#[test]
fn returning_cohort_repeats_outbound_and_return_replace_cycles() {
    let mut trajectories = Vec::new();
    for invert in [false, true] {
        let mut frame = fixture(invert, COHORT);
        let mut state = TrafficState::default();
        let mut returns = Vec::new();
        for cycle in 0..5 {
            if cycle > 0 {
                for unit in frame.units.iter_mut().filter(|u| u.owner_slot == 0) {
                    let id = if invert {
                        10000 - unit.unit_id
                    } else {
                        unit.unit_id
                    };
                    let goal = COHORT.iter().find(|r| r.0 == id).unwrap().2;
                    unit.target = Some(
                        Vec2::from_array(goal)
                            + if cycle % 2 == 1 {
                                Vec2::new(48., 0.)
                            } else {
                                Vec2::ZERO
                            },
                    );
                    unit.progress = None;
                    unit.plain_progress = None;
                    unit.physical_escape = None;
                    state.forget(unit.unit_id); // Ordinary same/new-target Replace retires traffic intent.
                }
            }
            for tick in (11 + cycle * 10)..=(20 + cycle * 10) {
                cohort_step(&mut frame, &mut state, tick, invert);
            }
            if cycle % 2 == 0 {
                returns.push(scout_positions(&frame, invert, 20 + cycle * 10));
            }
        }
        trajectories.push(returns);
    }
    assert_eq!(trajectories[0], trajectories[1]);
}
